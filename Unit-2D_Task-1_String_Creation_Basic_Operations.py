# Python program to demonstrate string creation and basic operations

# String creation
str1 = "Hello"
str2 = "World"

print("String 1:", str1)
print("String 2:", str2)

# Concatenation
concat = str1 + " " + str2
print("Concatenation:", concat)

# Repetition
repeat = str1 * 3
print("Repetition:", repeat)

# Slicing
print("First 3 characters of str1:", str1[:3])
print("Last 3 characters of str2:", str2[-3:])
print("Characters from index 1 to 4 in str1:", str1[1:5])