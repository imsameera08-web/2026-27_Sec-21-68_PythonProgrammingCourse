# Demonstrating Operator Precedence and Associativity

# Operator Precedence
result1 = 10 + 5 * 2
print("10 + 5 * 2 =", result1)

# Using brackets to change precedence
result2 = (10 + 5) * 2
print("(10 + 5) * 2 =", result2)

# Operator Associativity
result3 = 20 - 5 - 3
print("20 - 5 - 3 =", result3)

result4 = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", result4)