# Demonstrating Type Conversion

# Integer to Float
a = 10
b = float(a)
print("Integer to Float:", b)

# Float to Integer
c = 10.5
d = int(c)
print("Float to Integer:", d)

# Integer to String
e = 25
f = str(e)
print("Integer to String:", f)

# String to Integer
g = "50"
h = int(g)
print("String to Integer:", h)

# String to Float
i = "12.5"
j = float(i)
print("String to Float:", j)